    @Test
    void changingBoundsOrCycleReopensExhaustedSequence() throws SQLException {
        try ( JdbcConnection jdbc = new JdbcConnection( true );
                Statement sql = jdbc.getConnection().createStatement() ) {
            try {
                sql.executeUpdate( "CREATE TABLE identity_reconfigured (pk INTEGER PRIMARY KEY, generated_id SMALLINT GENERATED BY DEFAULT AS IDENTITY (MAXVALUE 3))" );
                assertArrayEquals( new long[]{ 1 }, returning( sql, "INSERT INTO identity_reconfigured (pk) VALUES (1) RETURNING generated_id" ) );
                assertArrayEquals( new long[]{ 2 }, returning( sql, "INSERT INTO identity_reconfigured (pk) VALUES (2) RETURNING generated_id" ) );
                assertArrayEquals( new long[]{ 3 }, returning( sql, "INSERT INTO identity_reconfigured (pk) VALUES (3) RETURNING generated_id" ) );
                assertThrows( SQLException.class, () -> sql.executeUpdate( "INSERT INTO identity_reconfigured (pk) VALUES (4)" ) );
                sql.executeUpdate( "ALTER TABLE identity_reconfigured ALTER COLUMN generated_id SET CYCLE" );
                sql.executeUpdate( "ALTER TABLE identity_reconfigured ALTER COLUMN generated_id SET MAXVALUE 5" );
                assertArrayEquals( new long[]{ 4 }, returning( sql, "INSERT INTO identity_reconfigured (pk) VALUES (4) RETURNING generated_id" ) );
                sql.executeUpdate( "ALTER TABLE identity_reconfigured ALTER COLUMN generated_id SET (MAXVALUE 4 CYCLE)" );
                assertArrayEquals( new long[]{ 1 }, returning( sql, "INSERT INTO identity_reconfigured (pk) VALUES (5) RETURNING generated_id" ) );
            } finally {
                sql.executeUpdate( "DROP TABLE IF EXISTS identity_reconfigured" );
            }
        }
    }


    @Test
    void returningRemainsUsableAsAnUnquotedIdentifier() throws SQLException {
        try ( JdbcConnection jdbc = new JdbcConnection( true );
                Statement sql = jdbc.getConnection().createStatement() ) {
            try {
                sql.executeUpdate( "CREATE TABLE returning (id INTEGER PRIMARY KEY, returning INTEGER)" );
                sql.executeUpdate( "INSERT INTO returning VALUES (1, 8)" );
                sql.executeUpdate( "UPDATE returning SET returning = 9 WHERE id = 1" );
                assertEquals( List.of( 9L ), numbers( sql, "SELECT returning FROM returning" ) );
                assertArrayEquals( new long[]{ 10 }, returning( sql, "INSERT INTO returning SELECT 2, returning + 1 FROM returning RETURNING returning" ) );
                assertArrayEquals( new long[]{ 11 }, returning( sql, "INSERT INTO returning SELECT 3, 11 returning RETURNING returning" ) );
                sql.executeUpdate( "INSERT INTO returning SELECT 4, 12 returning" );
                assertArrayEquals( new long[]{ 13 }, returning( sql, "INSERT INTO returning SELECT 5, returning.returning + 1 FROM returning returning WHERE id = 4 RETURNING returning" ) );
                assertEquals( List.of( 9L, 10L, 11L, 12L, 13L ), numbers( sql, "SELECT returning FROM returning ORDER BY id" ) );
            } finally {
                sql.executeUpdate( "DROP TABLE IF EXISTS returning" );
            }
        }
    }


    @Test
    void serialTypesAndSequenceOptionsThroughSql() throws SQLException {
        try ( JdbcConnection jdbc = new JdbcConnection( true );
                Statement sql = jdbc.getConnection().createStatement() ) {
            try {
                sql.executeUpdate( "CREATE TABLE identity_ddl (a SMALLSERIAL PRIMARY KEY, b SERIAL, c BIGSERIAL, d BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 9223372036854775807))" );
                assertArrayEquals( new long[]{ 1, 1, 1, Long.MAX_VALUE }, returning( sql, "INSERT INTO identity_ddl DEFAULT VALUES RETURNING *" ) );
                assertThrows( SQLException.class, () -> sql.executeUpdate( "INSERT INTO identity_ddl DEFAULT VALUES" ) );
                sql.executeUpdate( "ALTER TABLE identity_ddl ALTER COLUMN a RESTART WITH 100" );
                sql.executeUpdate( "ALTER TABLE identity_ddl ALTER COLUMN b RESTART WITH 2" );
                sql.executeUpdate( "ALTER TABLE identity_ddl ALTER COLUMN b SET (INCREMENT BY 10 MAXVALUE 1000)" );
                sql.executeUpdate( "ALTER TABLE identity_ddl ALTER COLUMN c SET START WITH 500" );
                sql.executeUpdate( "ALTER TABLE identity_ddl ALTER COLUMN c RESTART" );
                sql.executeUpdate( "ALTER TABLE identity_ddl ALTER COLUMN d RESTART WITH 7" );
                assertThrows( SQLException.class, () -> sql.executeUpdate( "ALTER TABLE identity_ddl ALTER COLUMN a RESTART WITH 32768" ) );
                assertArrayEquals( new long[]{ 100, 2, 500, 7 }, returning( sql, "INSERT INTO identity_ddl DEFAULT VALUES RETURNING a, b, c, d" ) );
                sql.executeUpdate( "TRUNCATE TABLE identity_ddl CONTINUE IDENTITY" );
                assertArrayEquals( new long[]{ 101, 12, 501, 8 }, returning( sql, "INSERT INTO identity_ddl DEFAULT VALUES RETURNING *" ) );
                sql.executeUpdate( "TRUNCATE TABLE identity_ddl RESTART IDENTITY" );
                assertArrayEquals( new long[]{ 1, 1, 500, Long.MAX_VALUE }, returning( sql, "INSERT INTO identity_ddl DEFAULT VALUES RETURNING *" ) );
            } finally {
                sql.executeUpdate( "DROP TABLE IF EXISTS identity_ddl" );
            }
        }
    }


    @Test
    void addColumnsAndIdentityToPopulatedTables() throws SQLException {
        try ( JdbcConnection jdbc = new JdbcConnection( true );
                Statement sql = jdbc.getConnection().createStatement() ) {
            try {
                sql.executeUpdate( "CREATE TABLE identity_backfill (pk INTEGER PRIMARY KEY, existing BIGINT NOT NULL)" );
                sql.executeUpdate( "INSERT INTO identity_backfill VALUES (1, 30), (2, 60)" );
                assertThrows( SQLException.class, () -> sql.executeUpdate(
                        "ALTER TABLE identity_backfill ADD COLUMN new_key BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 9223372036854775807)" ) );
                sql.executeUpdate( "ALTER TABLE identity_backfill ADD COLUMN new_key BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 5)" );
                assertEquals( List.of( 100L, 105L ), numbers( sql, "SELECT new_key FROM identity_backfill ORDER BY new_key" ) );
                sql.executeUpdate( "ALTER TABLE identity_backfill ALTER COLUMN existing ADD GENERATED BY DEFAULT AS IDENTITY" );
                assertArrayEquals( new long[]{ 61, 110 }, returning( sql, "INSERT INTO identity_backfill (pk) VALUES (3) RETURNING existing, new_key" ) );
                sql.executeUpdate( "ALTER TABLE identity_backfill ALTER COLUMN existing SET GENERATED ALWAYS" );
                assertThrows( SQLException.class, () -> sql.executeUpdate( "INSERT INTO identity_backfill (pk, existing) VALUES (4, 90)" ) );
                sql.executeUpdate( "ALTER TABLE identity_backfill ALTER COLUMN existing DROP IDENTITY" );
                assertEquals( 1, sql.executeUpdate( "INSERT INTO identity_backfill (pk, existing) VALUES (4, 90)" ) );
                assertEquals( List.of( 30L, 60L, 61L, 90L ), numbers( sql, "SELECT existing FROM identity_backfill ORDER BY pk" ) );
            } finally {
                sql.executeUpdate( "DROP TABLE IF EXISTS identity_backfill" );
            }
        }
    }


    @Test
    void identityBackfillRejectsDuplicatePrimaryKeysBeforeAddingColumn() throws SQLException {
        try ( JdbcConnection jdbc = new JdbcConnection( true );
                Statement sql = jdbc.getConnection().createStatement() ) {
            TestHelper.addHsqldb( "identity_duplicate_store", sql );
            try {
                // The fixture needs to store duplicate keys before running the backfill check.
                sql.executeUpdate( "CREATE TABLE identity_duplicate_pk (pk INTEGER PRIMARY KEY, label INTEGER) ON STORE identity_duplicate_store" );
                sql.executeUpdate( "INSERT INTO identity_duplicate_pk VALUES (1, 10), (1, 20)" );
                SQLException failure = assertThrows( SQLException.class, () -> sql.executeUpdate(
                        "ALTER TABLE identity_duplicate_pk ADD COLUMN generated_id SERIAL" ) );
                assertTrue( failure.getMessage().contains( "duplicate primary keys" ) );
                assertThrows( SQLException.class, () -> sql.executeQuery( "SELECT generated_id FROM identity_duplicate_pk" ) );
                assertEquals( List.of( 10L, 20L ), numbers( sql, "SELECT label FROM identity_duplicate_pk ORDER BY label" ) );
            } finally {
                try {
                    sql.executeUpdate( "DROP TABLE IF EXISTS identity_duplicate_pk" );
                } finally {
                    TestHelper.dropAdapter( "identity_duplicate_store", sql );
                }
            }
        }
    }


    @Test
    void addIdentityBackfillsEveryPartitionAcrossSplitPlacements() throws SQLException {
        try ( JdbcConnection jdbc = new JdbcConnection( true );
                Statement sql = jdbc.getConnection().createStatement() ) {
            boolean addedStore = false;
            try {
                sql.executeUpdate( "CREATE TABLE identity_split_backfill (id INTEGER PRIMARY KEY) PARTITION BY HASH (id) WITH (p0, p1, p2)" );
                sql.executeUpdate( "INSERT INTO identity_split_backfill VALUES (1), (2), (3), (4), (5), (6), (7), (8), (9)" );
                TestHelper.addHsqldb( "identity_split_backfill_store", sql );
                addedStore = true;
                sql.executeUpdate( "ALTER TABLE identity_split_backfill ADD PLACEMENT ON STORE identity_split_backfill_store" );
                sql.executeUpdate( "ALTER TABLE identity_split_backfill MODIFY PARTITIONS (p0) ON STORE hsqldb" );
                sql.executeUpdate( "ALTER TABLE identity_split_backfill MODIFY PARTITIONS (p1, p2) ON STORE identity_split_backfill_store" );

                sql.executeUpdate( "ALTER TABLE identity_split_backfill ADD COLUMN generated_id BIGSERIAL" );
                assertEquals( LongStream.rangeClosed( 1, 9 ).boxed().toList(),
                        numbers( sql, "SELECT generated_id FROM identity_split_backfill ORDER BY generated_id" ) );
                assertArrayEquals( new long[]{ 10 }, returning( sql,
                        "INSERT INTO identity_split_backfill (id) VALUES (10) RETURNING generated_id" ) );
            } finally {
                sql.executeUpdate( "DROP TABLE IF EXISTS identity_split_backfill" );
                if ( addedStore ) {
                    sql.executeUpdate( "ALTER ADAPTERS DROP identity_split_backfill_store" );
                }
            }
        }
    }


