    @Test
    void rollbackConsumesValuesAndAnExplicitRestartMayCollide() throws SQLException {
        Enum<?> previousPlacement = RuntimeConfig.DEFAULT_INDEX_PLACEMENT_STRATEGY.getEnum();
        RuntimeConfig.DEFAULT_INDEX_PLACEMENT_STRATEGY.setEnum( DefaultIndexPlacementStrategy.POLYPHENY );
        try ( JdbcConnection jdbc = new JdbcConnection( false );
                Statement sql = jdbc.getConnection().createStatement() ) {
            try {
                sql.executeUpdate( "CREATE TABLE identity_rollback (id INTEGER AUTO_INCREMENT PRIMARY KEY)" );
                sql.executeUpdate( "ALTER TABLE identity_rollback ADD UNIQUE INDEX identity_rollback_unique ON id" );
                assertArrayEquals( new long[]{ 1 }, returning( sql, "INSERT INTO identity_rollback DEFAULT VALUES RETURNING id" ) );
                jdbc.getConnection().rollback();
                assertArrayEquals( new long[]{ 2 }, returning( sql, "INSERT INTO identity_rollback DEFAULT VALUES RETURNING id" ) );
                jdbc.getConnection().commit();
                sql.executeUpdate( "ALTER TABLE identity_rollback ALTER COLUMN id RESTART WITH 2" );
                assertThrows( SQLException.class, () -> sql.executeUpdate( "INSERT INTO identity_rollback DEFAULT VALUES" ) );
                jdbc.getConnection().rollback();
                assertEquals( List.of( 2L ), numbers( sql, "SELECT id FROM identity_rollback" ) );
                assertArrayEquals( new long[]{ 3 }, returning( sql, "INSERT INTO identity_rollback DEFAULT VALUES RETURNING id" ) );
                jdbc.getConnection().commit();
                sql.executeUpdate( "TRUNCATE TABLE identity_rollback RESTART IDENTITY" );
                assertArrayEquals( new long[]{ 1 }, returning( sql, "INSERT INTO identity_rollback DEFAULT VALUES RETURNING id" ) );
                assertArrayEquals( new long[]{ 2 }, returning( sql, "INSERT INTO identity_rollback DEFAULT VALUES RETURNING id" ) );
                jdbc.getConnection().commit();
            } finally {
                jdbc.getConnection().rollback();
                sql.executeUpdate( "DROP TABLE IF EXISTS identity_rollback" );
            }
        } finally {
            RuntimeConfig.DEFAULT_INDEX_PLACEMENT_STRATEGY.setEnum( previousPlacement );
        }
    }


    @Test
    void concurrentClientsReceiveDisjointIds() throws Exception {
        try ( JdbcConnection jdbc = new JdbcConnection( true );
                Statement sql = jdbc.getConnection().createStatement() ) {
            sql.executeUpdate( "CREATE TABLE identity_concurrent (id BIGSERIAL PRIMARY KEY)" );
            ExecutorService workers = Executors.newFixedThreadPool( 4 );
            try {
                Callable<Void> insert = () -> {
                    try ( JdbcConnection client = new JdbcConnection( true );
                            Statement clientSql = client.getConnection().createStatement() ) {
                        for ( int i = 0; i < 5; i++ ) {
                            assertEquals( 1, clientSql.executeUpdate( "INSERT INTO identity_concurrent DEFAULT VALUES" ) );
                        }
                    }
                    return null;
                };
                for ( Future<Void> task : workers.invokeAll( List.of( insert, insert, insert, insert ), 25, TimeUnit.SECONDS ) ) {
                    task.get();
                }
                assertEquals( LongStream.rangeClosed( 1, 20 ).boxed().toList(),
                        numbers( sql, "SELECT id FROM identity_concurrent ORDER BY id" ) );
            } finally {
                workers.shutdownNow();
                sql.executeUpdate( "DROP TABLE IF EXISTS identity_concurrent" );
            }
        }
    }


    private static long[] returning( Statement statement, String query ) throws SQLException {
        try ( ResultSet result = statement.executeQuery( query ) ) {
            assertTrue( result.next() );
            long[] values = new long[result.getMetaData().getColumnCount()];
            for ( int i = 0; i < values.length; i++ ) {
                values[i] = result.getLong( i + 1 );
                assertFalse( result.wasNull() );
            }
            assertFalse( result.next() );
            return values;
        }
    }


    private static List<Long> numbers( Statement statement, String query ) throws SQLException {
        try ( ResultSet result = statement.executeQuery( query ) ) {
            List<Long> values = new ArrayList<>();
            while ( result.next() ) {
                values.add( result.getLong( 1 ) );
                assertFalse( result.wasNull() );
            }
            return values;
        }
    }

