package org.polypheny.db.webui.models.catalog;


import com.fasterxml.jackson.annotation.JsonProperty;
import org.polypheny.db.catalog.entity.LogicalDefaultValue;
import org.polypheny.db.catalog.entity.logical.IdentityColumn;
import org.polypheny.db.catalog.entity.logical.IdentityColumn.Mode;
import org.polypheny.db.catalog.entity.logical.LogicalColumn;


/**
 * Identity configuration shared by catalog responses and column requests.
 * Numeric options preserve signed 64-bit values in JavaScript.
 */
public record IdentityColumnModel(
        @JsonProperty Mode mode,
        @JsonProperty String start,
        @JsonProperty String increment,
        @JsonProperty String min,
        @JsonProperty String max,
        @JsonProperty boolean cycle ) {

    /**
     * Legacy data views omit an untouched input only when the result header contains a default.
     * The schema snapshot continues to expose literal defaults and identities separately.
     */
    public static String dataHeaderDefault( LogicalColumn column ) {
        IdentityColumn identity = column.getIdentity();
        if ( identity != null ) {
            return identity.mode() == Mode.ALWAYS ? "GENERATED ALWAYS AS IDENTITY" : "GENERATED BY DEFAULT AS IDENTITY";
        }
        LogicalDefaultValue literal = column.getLiteralDefaultValue();
        return literal == null ? null : literal.value.toJson();
    }


    public static IdentityColumnModel from( IdentityColumn identity ) {
        return identity == null ? null : new IdentityColumnModel(
                identity.mode(),
                Long.toString( identity.start() ),
                Long.toString( identity.increment() ),
                Long.toString( identity.min() ),
                Long.toString( identity.max() ),
                identity.cycle() );
    }

}
